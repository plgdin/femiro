-- Femiro production data, roles, RLS, and image storage.
-- Run once in Supabase SQL Editor.

create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text,
  role text not null default 'user' check (role in ('user', 'employee', 'admin')),
  created_at timestamptz not null default now()
);

alter table public.profiles add column if not exists display_name text;
alter table public.profiles add column if not exists role text not null default 'user';

create table if not exists public.products (
  id bigint primary key generated by default as identity,
  name text not null,
  type text not null,
  price numeric(12,2) not null check (price >= 0),
  old_price numeric(12,2),
  image text not null,
  hover text not null,
  tag text,
  description text not null,
  colors text[] not null default '{}',
  sizes text[] not null default '{}',
  has_colors boolean not null default false,
  in_stock boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.categories (
  name text primary key,
  created_at timestamptz not null default now()
);

create table if not exists public.hero_settings (
  id boolean primary key default true check (id),
  eyebrow text not null,
  headline text not null,
  subtitle text not null,
  image_url text not null,
  button_text text not null,
  button_link text not null default '/shop',
  updated_at timestamptz not null default now()
);

create table if not exists public.discounts (
  id uuid primary key default gen_random_uuid(),
  code text not null unique,
  discount_percent numeric(5,2) not null check (discount_percent >= 0 and discount_percent <= 100),
  fixed_amount numeric(12,2),
  type text not null default 'percent' check (type in ('percent', 'fixed')),
  min_spend numeric(12,2) not null default 0 check (min_spend >= 0),
  scope text not null default 'storewide' check (scope in ('storewide', 'category', 'products')),
  category_target text,
  product_ids bigint[] not null default '{}',
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.addresses (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null,
  mobile text not null,
  street text not null,
  city text not null,
  state text not null,
  pincode text not null,
  landmark text,
  tag text not null check (tag in ('Home', 'Office', 'Other')),
  is_default boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete restrict,
  items jsonb not null,
  total numeric(12,2) not null check (total >= 0),
  currency text not null default 'INR' check (currency = 'INR'),
  status text not null default 'Processing' check (status in ('Processing', 'Shipped', 'Delivered', 'Cancelled', 'Payment Pending')),
  delivery_address text not null,
  customer_email text,
  customer_phone text,
  razorpay_order_id text unique,
  razorpay_payment_id text unique,
  paid_at timestamptz,
  created_at timestamptz not null default now()
);

