drop policy if exists profiles_self_read on public.profiles;
create policy profiles_self_read on public.profiles for select using (id = auth.uid() or public.is_admin());
drop policy if exists profiles_admin_write on public.profiles;
create policy profiles_admin_write on public.profiles for update using (public.is_admin()) with check (public.is_admin());

drop policy if exists products_public_read on public.products;
create policy products_public_read on public.products for select using (true);
drop policy if exists products_staff_write on public.products;
create policy products_staff_write on public.products for all using (public.is_staff()) with check (public.is_staff());

drop policy if exists categories_public_read on public.categories;
create policy categories_public_read on public.categories for select using (true);
drop policy if exists categories_admin_write on public.categories;
create policy categories_admin_write on public.categories for all using (public.is_admin()) with check (public.is_admin());

drop policy if exists hero_public_read on public.hero_settings;
create policy hero_public_read on public.hero_settings for select using (true);
drop policy if exists hero_admin_write on public.hero_settings;
create policy hero_admin_write on public.hero_settings for all using (public.is_admin()) with check (public.is_admin());

drop policy if exists discounts_public_read_active on public.discounts;
create policy discounts_public_read_active on public.discounts for select using (active = true or public.is_staff());
drop policy if exists discounts_admin_write on public.discounts;
create policy discounts_admin_write on public.discounts for all using (public.is_admin()) with check (public.is_admin());

drop policy if exists addresses_owner_all on public.addresses;
create policy addresses_owner_all on public.addresses for all using (user_id = auth.uid()) with check (user_id = auth.uid());

drop policy if exists orders_owner_read on public.orders;
create policy orders_owner_read on public.orders for select using (user_id = auth.uid() or public.is_staff());
drop policy if exists orders_staff_update on public.orders;
create policy orders_staff_update on public.orders for update using (public.is_staff()) with check (public.is_staff());

